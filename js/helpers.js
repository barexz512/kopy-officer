const HARI_ID = [
  'Minggu',
  'Senin',
  'Selasa',
  'Rabu',
  'Kamis',
  'Jumat',
  'Sabtu'
];

const BULAN_ID = [
  'Januari',
  'Februari',
  'Maret',
  'April',
  'Mei',
  'Juni',
  'Juli',
  'Agustus',
  'September',
  'Oktober',
  'November',
  'Desember'
];

const BULAN_ROMAWI = [
  'I', 'II', 'III', 'IV', 'V', 'VI',
  'VII', 'VIII', 'IX', 'X', 'XI', 'XII'
];

/**
 * Mengembalikan tanggal hari ini dalam format resmi Bahasa Indonesia.
 * Contoh: "Rabu, 18 November 2026"
 */
export function formatTanggalIndonesia(date = new Date(), withDay = true) {
  const hari = HARI_ID[date.getDay()];
  const tanggal = date.getDate();
  const bulan = BULAN_ID[date.getMonth()];
  const tahun = date.getFullYear();
  return withDay ? `${hari}, ${tanggal} ${bulan} ${tahun}` : `${tanggal} ${bulan} ${tahun}`;
}

/**
 * Mengembalikan bulan Romawi saat ini untuk format nomor surat Indonesia.
 */
export function getBulanRomawi(date = new Date()) {
  return BULAN_ROMAWI[date.getMonth()];
}

/**
 * Mengembalikan sapaan pengguna sesuai waktu lokal perangkat.
 */
export function getSapaanWaktu(date = new Date()) {
  const jam = date.getHours();
  if (jam >= 4 && jam < 11) return 'Selamat Pagi';
  if (jam >= 11 && jam < 15) return 'Selamat Siang';
  if (jam >= 15 && jam < 18) return 'Selamat Sore';
  return 'Selamat Malam';
}

/**
 * Mencegah XSS saat merender input pengguna ke HTML.
 */
export function escapeHTML(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Menampilkan notifikasi singkat di pojok layar.
 */
export function showToast(message) {
  const container = document.getElementById('toast-container');
  if (!container) return;

  const toast = document.createElement('div');
  toast.className = 'toast';
  toast.textContent = message;
  container.appendChild(toast);

  window.setTimeout(() => {
    toast.remove();
  }, 3200);
}

